import assert from "node:assert/strict";
import {mkdtemp,mkdir,writeFile,readFile,rm,symlink} from "node:fs/promises";
import {tmpdir} from "node:os";
import {join} from "node:path";
import test from "node:test";
import express from "express";
import {copyWorkspaceFile} from "./file-operations.js";
import {ArtifactExports,registerExportRoute} from "./artifact-exports.js";
test("binary copies and moves never overwrite destinations or escape through links",async t=>{
 const dir=await mkdtemp(join(tmpdir(),"devspace-fileops-"));t.after(()=>rm(dir,{recursive:true,force:true}));
 const root=join(dir,"project");await mkdir(root);
 const bytes=Buffer.from([0,1,255,128,65]);const source=join(root,"source.bin");await writeFile(source,bytes);
 await copyWorkspaceFile(root,source,join(root,"copy.bin"));
 assert.deepEqual(await readFile(join(root,"copy.bin")),bytes);
 await assert.rejects(copyWorkspaceFile(root,source,join(root,"copy.bin")),/EEXIST/);
 await copyWorkspaceFile(root,source,join(root,"moved.bin"),true);
 await assert.rejects(readFile(source),/ENOENT/);assert.deepEqual(await readFile(join(root,"moved.bin")),bytes);
 await symlink(dir,join(root,"escape"));
 await assert.rejects(copyWorkspaceFile(root,join(root,"copy.bin"),join(root,"escape","outside.bin")),/outside/);
 await assert.rejects(readFile(join(dir,"outside.bin")),/ENOENT/);
});
test("export returns an immutable downloadable copy with file-specific expiry",async t=>{
 const dir=await mkdtemp(join(tmpdir(),"devspace-export-"));t.after(()=>rm(dir,{recursive:true,force:true}));
 const root=join(dir,"project"),state=join(dir,"state");await mkdir(root);await writeFile(join(root,"成品.bin"),Buffer.from([0,255,12]));
 const exports=new ArtifactExports(join(state,"exports"));
 const record=await exports.create("ws",root,join(root,"成品.bin"),"application/octet-stream",60);
 await writeFile(join(root,"成品.bin"),"changed");
 const app=express();registerExportRoute(app,state);
 const server=app.listen(0,"127.0.0.1");await new Promise<void>(resolve=>server.once("listening",resolve));
 t.after(()=>new Promise<void>((resolve,reject)=>{server.close(error=>error?reject(error):resolve());server.closeAllConnections();}));
 const address=server.address();assert.ok(address && typeof address!=="string");
 const origin="http://127.0.0.1:"+address.port;
 const response=await fetch(origin+"/artifacts/download?token="+record.token);
 assert.equal(response.status,200);assert.deepEqual(Buffer.from(await response.arrayBuffer()),Buffer.from([0,255,12]));
 assert.match(response.headers.get("content-disposition")??"",/attachment/);
 assert.equal((await fetch(origin+"/artifacts/download?token="+"0".repeat(64))).status,404);
 const expired=await exports.create("ws",root,join(root,"成品.bin"),"application/octet-stream",-1);
 assert.equal((await fetch(origin+"/artifacts/download?token="+expired.token)).status,404);
 await exports.cleanup();await assert.rejects(exports.get(expired.token));
});
